import os
import logging
from typing import List, Optional

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, pipeline, Pipeline

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO)


def _detect_device(device: Optional[int] = None) -> str:
    """
    Resolve the torch device string based on the provided index or environment.

    Args:
        device: Optional CUDA device index. If ``None`` the function will
            automatically select ``cuda`` when available, otherwise ``cpu``.

    Returns:
        A device string compatible with ``torch.device``.
    """
    if device is not None:
        return f"cuda:{device}" if torch.cuda.is_available() else "cpu"
    return "cuda" if torch.cuda.is_available() else "cpu"


def _build_prompt(code: str, diff: Optional[str] = None) -> str:
    """
    Construct a prompt for the LLM that asks for a concise code review.

    The prompt includes a short system instruction and the code (and optional diff)
    that should be reviewed.

    Args:
        code: The source code to be reviewed.
        diff: An optional unified diff describing recent changes.

    Returns:
        A string prompt ready to be fed to the language model.
    """
    instruction = (
        "You are an expert software engineer. Provide a short, constructive code review. "
        "List each comment as a separate bullet point. Focus on correctness, readability, "
        "performance, and best practices. Do not include explanations beyond the comment itself."
    )
    parts = [instruction, "\n\n---\n\n", "Code:\n", code]
    if diff:
        parts.extend(["\n\nDiff:\n", diff])
    parts.append("\n\nReview:")
    return "".join(parts)


def _parse_output(output_text: str) -> List[str]:
    """
    Transform raw model output into a list of clean comment strings.

    The model is prompted to emit bullet points (e.g., starting with ``-`` or ``*``).
    This parser extracts each bullet and strips surrounding whitespace.

    Args:
        output_text: The raw text generated by the model.

    Returns:
        A list of individual review comments.
    """
    lines = output_text.strip().splitlines()
    comments: List[str] = []
    for line in lines:
        stripped = line.lstrip()
        # Accept typical bullet markers
        if stripped.startswith(("-", "*")):
            comment = stripped[1:].strip()
            if comment:
                comments.append(comment)
        elif stripped:  # Fallback: treat any non‑empty line as a comment
            comments.append(stripped)
    return comments


class CodeReviewer:
    """
    A lightweight wrapper around a causal language model that generates code review comments.

    Example
    -------
    >>> reviewer = CodeReviewer(model_name="gpt2")
    >>> comments = reviewer.generate("def add(a,b):return a+b")
    >>> isinstance(comments, list)
    True
    """

    def __init__(self, model_name: str = "gpt2", device: Optional[int] = None, **gen_kwargs):
        """
        Initialise the reviewer.

        Parameters
        ----------
        model_name: str
            The HuggingFace model identifier. Defaults to ``gpt2`` which is small
            and always available.
        device: Optional[int]
            CUDA device index. If ``None`` the class will automatically select
            ``cuda`` when a GPU is present, otherwise ``cpu``.
        gen_kwargs: dict
            Additional keyword arguments passed to the text generation pipeline
            (e.g., ``temperature``, ``max_new_tokens``). Reasonable defaults are
            applied if not supplied.
        """
        self.model_name = model_name
        self.device_str = _detect_device(device)
        self.gen_kwargs = {
            "max_new_tokens": 256,
            "temperature": 0.7,
            "do_sample": True,
            "pad_token_id": 50256,  # GPT‑2 compatible padding token
            **gen_kwargs,
        }

        logger.info("Loading model '%s' on device %s", model_name, self.device_str)
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForCausalLM.from_pretrained(
            model_name,
            torch_dtype=torch.float16 if "cuda" in self.device_str else torch.float32,
            device_map="auto",
        )
        self.generator: Pipeline = pipeline(
            "text-generation",
            model=self.model,
            tokenizer=self.tokenizer,
            device=0 if "cuda" in self.device_str else -1,
        )
        logger.info("Model loaded successfully.")

    def generate(self, code: str, diff: Optional[str] = None, **override_kwargs) -> List[str]:
        """
        Generate review comments for the supplied code (and optional diff).

        Parameters
        ----------
        code: str
            The source code to review.
        diff: Optional[str]
            A unified diff string describing recent changes. If provided,
            the model will consider it when forming comments.
        override_kwargs: dict
            Generation parameters that override the defaults supplied at construction.

        Returns
        -------
        List[str]
            A list of bullet‑point comments produced by the LLM.
        """
        if not code.strip():
            raise ValueError("`code` must be a non‑empty string.")

        prompt = _build_prompt(code, diff)
        gen_params = {**self.gen_kwargs, **override_kwargs}
        logger.debug("Generating review with params: %s", gen_params)

        # The pipeline returns a list of dicts with a ``generated_text`` key.
        result = self.generator(prompt, **gen_params)
        generated_text = result[0]["generated_text"][len(prompt) :]  # strip the prompt

        comments = _parse_output(generated_text)
        logger.info("Generated %d review comment(s).", len(comments))
        return comments

    __call__ = generate  # Alias to allow instance usage as a function.